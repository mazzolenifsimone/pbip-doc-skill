    @classmethod
    def _coerce_value(cls, current_val: Any, new_val: Any) -> Any:
        if current_val is None:
            if isinstance(new_val, str) and not new_val.strip():
                return None
            return str(new_val) if new_val is not None else None
        elif isinstance(current_val, bool):
            if isinstance(new_val, bool):
                return new_val
            if isinstance(new_val, str):
                lower = new_val.strip().lower()
                if lower in ("true", "1", "yes", "on", "t"):
                    return True
                if lower in ("false", "0", "no", "off", "f"):
                    return False
            return bool(new_val)
        elif isinstance(current_val, int) and not isinstance(current_val, bool):
            try:
                return int(new_val)
            except (ValueError, TypeError):
                return current_val
        elif isinstance(current_val, list):
            if isinstance(new_val, list):
                return new_val
            if isinstance(new_val, str):
                clean = new_val.strip()
                if clean.startswith("[") and clean.endswith("]"):
                    try:
                        parsed = json.loads(clean)
                        if isinstance(parsed, list):
                            return parsed
                    except Exception:
                        pass
                return [item.strip() for item in clean.split(",") if item.strip()]
            return [new_val]
        elif isinstance(current_val, dict):
            if isinstance(new_val, dict):
                return new_val
            if isinstance(new_val, str):
                clean = new_val.strip()
                if clean.startswith("{") and clean.endswith("}"):
                    try:
                        parsed = json.loads(clean)
                        if isinstance(parsed, dict):
                            return parsed
                    except Exception:
                        pass
                pairs = {}
                for part in clean.split(","):
                    if "=" in part:
                        k, v = part.split("=", 1)
                        pairs[k.strip()] = v.strip()
                if pairs:
                    return pairs
            return current_val
        elif isinstance(current_val, str):
            return str(new_val)
        return new_val

    @classmethod
    def parse_set_arg(cls, set_expr: str) -> Tuple[str, str]:
        """Parses a 'key=value' CLI argument into a (key, raw_value) tuple."""
        if "=" not in set_expr:
            raise ValueError(f"Invalid --set expression '{set_expr}'. Expected format: key=value")
        key, val = set_expr.split("=", 1)
        return key.strip(), val.strip()

